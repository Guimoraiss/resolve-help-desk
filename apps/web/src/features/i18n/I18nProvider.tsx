type I18nContextValue = { locale: Locale; setLocale(locale: Locale): void; t(key: string): string };
const I18nContext = createContext<I18nContextValue | null>(null);
const storageKey = "resolve.locale";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem(storageKey);
    return stored === "en" || stored === "es" || stored === "fr" || stored === "de" ? stored : "pt-BR";
  });
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale(next) {
        localStorage.setItem(storageKey, next);
        setLocaleState(next);
      },
      t(key) {
        return translations[locale][key] ?? translations.en[key] ?? translations["pt-BR"][key] ?? key;
      },
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
